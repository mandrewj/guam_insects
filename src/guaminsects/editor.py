"""The taxonomy editor's Python side (the editor itself is static: editor/, see docs/EDITOR.md).

`spec()` is the vocabulary the editor shares with curation.py, taxonomy.py and geo.py
(columns, ranks, statuses, places, cell formats). `guaminsects editor-spec` writes it to
editor/assets/spec.js; tests/test_editor.py fails when that file is stale.

`serve()` is `guaminsects edit`: a small local server for a clone of the repository. It serves
the editor and the files it edits, and commits and pushes with the user's own git when the
editor's Commit button is pressed. It needs no database: the push triggers the rebuild
(.github/workflows/rebuild.yml). It binds to 127.0.0.1 only and serves nothing else.
"""

import functools
import http.server
import json
import subprocess
import tempfile
import urllib.parse
from pathlib import Path

from . import config, curation, geo, taxonomy

EDITOR_DIR = config.ROOT / "editor"
SPEC_JS = EDITOR_DIR / "assets" / "spec.js"
REPO = "mandrewj/guam_insects"
BRANCH = "main"
SITE_URL = "https://insects-of-guam.vercel.app/"
# The only files the editor reads and writes (paths relative to the repository root).
FILES = ["taxonomy.csv", "curation/taxa.csv", "curation/evidence.csv",
         "curation/annotations.csv"]


def spec() -> dict:
    from .site import AREA_SHORT

    places = []
    for a in config.AREA_CODES:
        places += [[n, a, True] for n, area in geo.GROUPS.items() if area == a]
        places += [[n, a, False] for n in geo.ISLAND_COORDS[a] if n not in geo.SKIP and
                   n not in geo.GROUPS]
    return {
        "repo": REPO, "branch": BRANCH, "site": SITE_URL, "files": FILES,
        "columns": taxonomy.COLUMNS, "editable": taxonomy.EDITABLE,
        "listColumns": taxonomy.LIST_COLUMNS, "levels": taxonomy.LEVELS,
        "sep": taxonomy.SEP, "inatObs": taxonomy.INAT_OBS, "gbifOcc": taxonomy.GBIF_OCC,
        "taxaColumns": curation.TAXA_COLUMNS, "overrideFields": curation.OVERRIDE_FIELDS,
        "evidenceColumns": curation.EVIDENCE_COLUMNS,
        "annotationColumns": curation.ANNOTATION_COLUMNS,
        "statuses": sorted(curation.STATUSES), "establishment": sorted(curation.ESTABLISHMENT),
        "evidenceKinds": sorted(curation.EVIDENCE_KINDS), "licenses": sorted(curation.LICENSES),
        "ranks": curation.RANKS, "distributionStatus": curation.DISTRIBUTION_STATUS,
        "places": places,
        "areas": [{"code": a["code"], "name": a["name"], "short": AREA_SHORT[a["code"]]}
                  for a in config.AREAS],
    }


def spec_js() -> str:
    body = json.dumps(spec(), indent=1, ensure_ascii=False)
    return ("// Generated by `uv run guaminsects editor-spec` from curation.py, taxonomy.py and\n"
            "// geo.py. Do not edit by hand; tests/test_editor.py checks it is current.\n"
            f"window.IOG_SPEC = {body};\n")


def write_spec() -> bool:
    text = spec_js()
    if SPEC_JS.exists() and SPEC_JS.read_text(encoding="utf-8") == text:
        return False
    SPEC_JS.parent.mkdir(parents=True, exist_ok=True)
    SPEC_JS.write_text(text, encoding="utf-8")
    return True


# ---------------------------------------------------------------- the local server

def _git(*args, cwd: Path | None = None, check: bool = True) -> str:
    r = subprocess.run(["git", *args], cwd=cwd or config.ROOT, capture_output=True, text=True,
                       timeout=120)
    if check and r.returncode:
        raise RuntimeError(f"git {' '.join(args)}: {(r.stderr or r.stdout).strip()}")
    return r.stdout.strip()


def validate(files: dict[str, str]) -> list[str]:
    """Check the curation files the editor wants to commit, as `resolve` would read them
    (everything but the tree itself, which needs the database: CI checks that)."""
    with tempfile.TemporaryDirectory() as d:
        root = Path(d)
        for rel in FILES[1:]:
            src = files.get(rel)
            text = src if src is not None else (
                (config.ROOT / rel).read_text(encoding="utf-8-sig")
                if (config.ROOT / rel).exists() else None)
            if text is not None:
                (root / Path(rel).name).write_text(text, encoding="utf-8")
        try:
            curation.load(root / "taxa.csv", root / "evidence.csv", assign_ids=False,
                          annotations_csv=root / "annotations.csv")
        except curation.CurationError as e:
            return str(e).split("\n")
    return []


def info() -> dict:
    remote = _git("remote", "get-url", "origin", check=False)
    dirty = [line[3:] for line in _git("status", "--porcelain", "--", *FILES).splitlines()]
    return {"mode": "local", "repo": remote, "branch": _git("rev-parse", "--abbrev-ref", "HEAD"),
            "head": _git("rev-parse", "HEAD"), "user": _git("config", "user.name", check=False),
            "dirty": dirty, "has_db": config.DB_PATH.exists()}


def commit(files: dict[str, str], message: str, author: str, base: str,
           push: bool = True) -> dict:
    """Write the files, commit them (author: the editor's 'added by' name), push."""
    unknown = sorted(set(files) - set(FILES))
    if unknown:
        return {"ok": False, "status": 400, "errors": [f"not an editor file: {', '.join(unknown)}"]}
    if not author.strip():
        return {"ok": False, "status": 400, "errors": ["a name (added by) is required"]}
    state = info()
    if state["head"] != base:
        return {"ok": False, "status": 409, "head": state["head"],
                "errors": ["the repository moved on since the editor loaded it; reload"]}
    if state["dirty"]:
        return {"ok": False, "status": 409, "errors": [
            "uncommitted changes in " + ", ".join(state["dirty"]) +
            ": commit or discard them first (git status)"]}
    errors = validate(files)
    if errors:
        return {"ok": False, "status": 400, "errors": errors}
    for rel, text in files.items():
        path = config.ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(path.suffix + ".tmp")
        tmp.write_bytes(text.encode("utf-8"))
        tmp.replace(path)
    email = _git("config", "user.email", check=False)
    _git("add", "--", *files)
    _git("commit", "-q", "-m", message, f"--author={author.strip()} <{email}>")
    sha = _git("rev-parse", "HEAD")
    out = {"ok": True, "sha": sha, "pushed": False}
    if push:
        r = subprocess.run(["git", "push", "-q", "origin", f"HEAD:{BRANCH}"], cwd=config.ROOT,
                           capture_output=True, text=True, timeout=120)
        if r.returncode:            # someone pushed first: replay this commit on theirs
            pull = subprocess.run(["git", "pull", "-q", "--rebase", "origin", BRANCH],
                                  cwd=config.ROOT, capture_output=True, text=True, timeout=120)
            if pull.returncode:
                _git("rebase", "--abort", check=False)
                out["error"] = ("committed locally, but the push was refused and the commit "
                                "does not replay cleanly on GitHub's main: run `git pull "
                                "--rebase` and resolve, then `git push`")
                return out
            r = subprocess.run(["git", "push", "-q", "origin", f"HEAD:{BRANCH}"],
                               cwd=config.ROOT, capture_output=True, text=True, timeout=120)
        out["pushed"] = r.returncode == 0
        out["sha"] = _git("rev-parse", "HEAD")
        if r.returncode:
            out["error"] = "committed locally; push failed: " + (r.stderr or r.stdout).strip()
    return out


class Handler(http.server.SimpleHTTPRequestHandler):
    push = True

    def log_message(self, fmt, *args):
        if self.path.startswith("/api/"):
            super().log_message(fmt, *args)

    def _json(self, obj, status: int = 200) -> None:
        body = json.dumps(obj, ensure_ascii=False).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _allowed(self, path: str) -> bool:
        p = urllib.parse.unquote(path.split("?")[0]).lstrip("/")
        return p in FILES or (p.startswith("editor/") and ".." not in p)

    def end_headers(self):
        self.send_header("Cache-Control", "no-store")
        super().end_headers()

    def do_GET(self):
        url = urllib.parse.urlsplit(self.path)
        if url.path in ("/", "/editor"):
            self.send_response(302)
            self.send_header("Location", "/editor/")
            self.end_headers()
            return None
        if url.path == "/api/editor/info":
            try:
                return self._json(info())
            except RuntimeError as e:
                return self._json({"error": str(e)}, 500)
        if not self._allowed(url.path):
            return self._json({"error": "not served"}, 404)
        return super().do_GET()

    def do_POST(self):
        if self.path != "/api/editor/commit":
            return self._json({"error": "unknown endpoint"}, 404)
        # Only the editor page itself may commit (a page from another site cannot).
        host = self.headers.get("Host", "")
        origin = self.headers.get("Origin")
        if origin and urllib.parse.urlsplit(origin).netloc != host:
            return self._json({"ok": False, "errors": ["cross-origin request refused"]}, 403)
        try:
            n = int(self.headers.get("Content-Length") or 0)
            data = json.loads(self.rfile.read(n) or b"{}")
            out = commit(data.get("files") or {}, str(data.get("message") or "Editor changes"),
                         str(data.get("author") or ""), str(data.get("base") or ""),
                         push=self.push)
        except (ValueError, RuntimeError) as e:
            return self._json({"ok": False, "errors": [str(e)]}, 500)
        return self._json(out, out.pop("status", 200))


def serve(port: int = 8766, push: bool = True) -> int:
    if not (EDITOR_DIR / "index.html").exists():
        print(f"no editor at {EDITOR_DIR}")
        return 1
    Handler.push = push
    handler = functools.partial(Handler, directory=str(config.ROOT))
    with http.server.ThreadingHTTPServer(("127.0.0.1", port), handler) as httpd:
        print(f"editor at http://localhost:{port}/editor/  (Ctrl-C to stop)"
              + ("" if push else "; commits stay local (--no-push)"))
        try:
            httpd.serve_forever()
        except KeyboardInterrupt:
            pass
    return 0
